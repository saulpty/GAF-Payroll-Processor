// Generates the seed_pto_from_excel migration from an extracted PTO workbook.
// Usage: node tools/pto-seed-from-xlsx.mjs <extracted-xlsx-dir> > out.sql
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/pto-seed-from-xlsx.mjs <extracted-xlsx-dir>'); process.exit(1); }
const dec = s => s.replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&quot;/g,'"').replace(/&apos;/g,"'");
const shared = existsSync(join(dir,'xl/sharedStrings.xml'))
  ? [...readFileSync(join(dir,'xl/sharedStrings.xml'),'utf8').matchAll(/<si>([\s\S]*?)<\/si>/g)]
      .map(m => dec([...m[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map(t=>t[1]).join('')))
  : [];
const wb = readFileSync(join(dir,'xl/workbook.xml'),'utf8');
const rels = readFileSync(join(dir,'xl/_rels/workbook.xml.rels'),'utf8');
const relMap = {};
for (const m of rels.matchAll(/<Relationship\b[^>]*>/g)) {
  const id = (m[0].match(/Id="([^"]+)"/)||[])[1], t = (m[0].match(/Target="([^"]+)"/)||[])[1];
  if (id && t) relMap[id] = t;
}
const sheets = {};
for (const m of wb.matchAll(/<sheet\b[^>]*>/g)) {
  const name = dec((m[0].match(/name="([^"]+)"/)||[])[1]||''), rid = (m[0].match(/r:id="([^"]+)"/)||[])[1];
  sheets[name] = join(dir,'xl',relMap[rid].replace(/^\/xl\//,''));
}
function rows(sheetName) {
  const xml = readFileSync(sheets[sheetName],'utf8');
  return [...xml.matchAll(/<row [^>]*r="(\d+)"[^>]*>([\s\S]*?)<\/row>/g)].map(r => {
    const cells = {};
    for (const c of r[2].matchAll(/<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g)) {
      const t = (c[2].match(/t="([^"]+)"/)||[])[1]; let v = (c[3]||'').match(/<v>([\s\S]*?)<\/v>/)?.[1];
      if (t==='s' && v!==undefined) v = shared[Number(v)];
      if (t==='inlineStr') v = dec([...(c[3]||'').matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map(x=>x[1]).join(''));
      if (v!==undefined) cells[c[1]] = v;
    }
    return { n: Number(r[1]), cells };
  });
}
// Excel serial → YYYY-MM-DD (1900 date system). Text dates pass through.
function toISO(v) {
  if (v === undefined || v === '') return null;
  if (/^\d{4}-\d{2}-\d{2}/.test(v)) return v.slice(0,10);
  const n = Number(v); if (!Number.isFinite(n)) return null;
  const ms = Math.round((n - 25569) * 86400000); return new Date(ms).toISOString().slice(0,10);
}
const q = s => "'" + String(s).replace(/'/g,"''") + "'";

const out = [];
out.push('-- Generated by tools/pto-seed-from-xlsx.mjs from PTO TRACKING GAF NEW.xlsx.');
out.push('-- Employees are matched by name at apply time; unknown names raise. Review before applying.');
out.push('DO $$ DECLARE missing text; BEGIN');
// ── which column-A values are actually people ────────────────────────────────
// The sheets carry footnote rows below the data (e.g. the "📌 Column G (FH Used)
// is a manual entry…" note at the bottom of Floating Holidays). Those land in
// column A and would otherwise be treated as employees.
function isPerson(raw) {
  const s = (raw || '').trim();
  if (!s) return false;
  if (s.length > 45) return false;                    // notes are long, names are not
  if (/[\u{1F300}-\u{1FAFF}☀-➿]/u.test(s)) return false;  // 📌 ✅ ⚠ etc
  if (/[:;]|\bColumn\b|\bmanual\b|\bautomatically\b/i.test(s)) return false;
  return true;
}

// Sheet spelling → the display_name actually stored in employees.
const NAME_MAP = {
  'Michael Jones': 'Michael Antonio Jones Roye',
};

// People deliberately not imported, with the reason recorded in the SQL header.
const SKIP = {
  'Johann Morante':
    'rehired 2026-08; owner decision 2026-08-19 to treat him as a brand-new employee, so no pre-rehire history is imported',
};

const skipped = [];
/** Returns the employees.display_name to match on, or null to skip this row. */
function resolveName(raw) {
  const s = (raw || '').trim();
  if (!isPerson(s)) return null;
  if (SKIP[s]) { if (!skipped.includes(s)) skipped.push(s); return null; }
  return NAME_MAP[s] || s;
}

const names = new Set();
for (const s of ['PTO-Balance','PTO Approvals','Floating Holidays']) {
  for (const r of rows(s)) {
    if (r.n < 4) continue;
    const n = resolveName(r.cells.A);
    if (n) names.add(n);
  }
}
out.push(`  SELECT string_agg(n, ', ') INTO missing FROM unnest(ARRAY[${[...names].map(q).join(',')}]) AS n WHERE NOT EXISTS (SELECT 1 FROM employees WHERE lower(display_name) = lower(n));`);
out.push("  IF missing IS NOT NULL THEN RAISE EXCEPTION 'Unknown employees in sheet: %', missing; END IF;");
out.push('END $$;');

// One set-based statement per table rather than one statement per row. The
// per-row form repeated a 250-character name-lookup subquery twice for every
// line and pushed the file past 50 KB, which is more than UI Bakery's chat box
// accepts — it silently truncates, which would apply a half-finished import.
const d = v => (v ? `DATE ${q(v)}` : 'NULL::date');

out.push('\n-- PTO-Balance: paid PTO, and a start-date override only where the');
out.push('-- sheet disagrees with the date already on the employee record.');
const balRows = [];
for (const r of rows('PTO-Balance')) {
  if (r.n < 4) continue;
  const name = resolveName(r.cells.A); if (!name) continue;
  balRows.push(`  (${q(name)}, ${Number(r.cells.G||0)||0}, ${d(toISO(r.cells.C))})`);
}
out.push('WITH src(nm, paid, ovr) AS (VALUES');
out.push(balRows.join(',\n'));
out.push(`)
INSERT INTO pto_employees (employee_id, paid_pto_days, pto_start_date_override)
SELECT e.id, s.paid,
       CASE WHEN e.start_date IS DISTINCT FROM s.ovr THEN s.ovr ELSE NULL END
FROM src s
JOIN employees e ON lower(e.display_name) = lower(s.nm)
ON CONFLICT (employee_id) DO UPDATE
  SET paid_pto_days           = EXCLUDED.paid_pto_days,
      pto_start_date_override = EXCLUDED.pto_start_date_override;`);

out.push('\n-- PTO Approvals: the historical ledger. NOT idempotent -- run once.');
const appRows = [];
for (const r of rows('PTO Approvals')) {
  if (r.n < 4 || !r.cells.D) continue;
  const name = resolveName(r.cells.A); if (!name) continue;
  const cmt = r.cells.G ? q(String(r.cells.G)) : 'NULL';
  appRows.push(`  (${q(name)}, ${d(toISO(r.cells.D))}, ${d(toISO(r.cells.E))}, ${Number(r.cells.F||0)||0}, ${cmt})`);
}
out.push('WITH src(nm, leave_on, return_on, days, cmt) AS (VALUES');
out.push(appRows.join(',\n'));
out.push(`)
INSERT INTO pto_approvals
  (employee_id, leave_on, return_on, total_days, status, source, gaf_comments, recorded_by, recorded_at)
SELECT e.id, s.leave_on, s.return_on, s.days,
       'recorded', 'excel_import', s.cmt::text, 'excel import', NOW()
FROM src s
JOIN employees e ON lower(e.display_name) = lower(s.nm);`);

const year = new Date().getFullYear();
out.push(`\n-- Floating Holidays used, calendar year ${year}. Allocated stays 2.`);
const fhRows = [];
for (const r of rows('Floating Holidays')) {
  if (r.n < 4) continue;
  const name = resolveName(r.cells.A); if (!name) continue;
  fhRows.push(`  (${q(name)}, ${Number(r.cells.G||0)||0})`);
}
out.push('WITH src(nm, used) AS (VALUES');
out.push(fhRows.join(',\n'));
out.push(`)
INSERT INTO pto_floating_holidays (employee_id, calendar_year, fh_allocated, fh_used)
SELECT e.id, ${year}, 2, s.used
FROM src s
JOIN employees e ON lower(e.display_name) = lower(s.nm)
ON CONFLICT (employee_id, calendar_year) DO UPDATE
  SET fh_used = EXCLUDED.fh_used;`);
// Record deliberate omissions in the file itself, so the decision travels with
// the SQL rather than living only in someone's memory.
const header = [];
if (skipped.length) {
  header.push('-- DELIBERATELY NOT IMPORTED:');
  for (const s of skipped) header.push(`--   ${s} — ${SKIP[s]}`);
}
if (Object.keys(NAME_MAP).length) {
  header.push('-- Sheet spelling mapped to the employees table:');
  for (const [from, to] of Object.entries(NAME_MAP)) header.push(`--   "${from}" -> "${to}"`);
}
if (header.length) out.splice(2, 0, ...header);

console.log(out.join('\n'));
